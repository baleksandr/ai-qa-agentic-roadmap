function studyBodyToMarkdown(body) {
  const lines = body.split('\n');
  const out = [];
  for (const line of lines) {
    const t = line.trim();
    if (!t) {
      out.push('');
      continue;
    }
    if (/^QUICK VIEW —/.test(t)) {
      out.push(`### ${t}`);
      continue;
    }
    if (/^\d+\.\d+(?:\.\d+)?\s/.test(t)) {
      out.push(`### ${t}`);
      continue;
    }
    if (/^\d+\.\s/.test(t) && t.length < 120) {
      out.push(`### ${t}`);
      continue;
    }
    if (
      /^(Ключова ідея|Interview answer|Питання:|Типові причини|Model vs|MODEL \/|AGENTIC|Input, output|Hands-on Lab)/.test(
        t,
      )
    ) {
      out.push(`**${t}**`);
      continue;
    }
    out.push(t);
  }
  return out.join('\n').trim();
}

function pickQuickView(body) {
  const idx = body.indexOf('QUICK VIEW —');
  if (idx < 0) return null;
  const rest = body.slice(idx + 'QUICK VIEW —'.length);
  const end = rest.search(/\n0\. Яку проблему/);
  const block = (end > 0 ? rest.slice(0, end) : rest.split('\n').slice(0, 3).join('\n')).trim();
  return block.replace(/\s+/g, ' ');
}

function fundamentalsReview() {
  return [
    '- AI / ML / Deep Learning / Generative AI — різні рівні; **LLM ≠ весь AI**.',
    '- LLM — probabilistic engine над токенами; надійність = context + tools + validation + evals.',
    '- Tokens і context window — ємність, latency, cost.',
    '- Training vs inference; hallucinations — лише з evidence та перевірками.',
  ].join('\n');
}

function sliceMammoth(md, startRe, endRe) {
  const start = md.search(startRe);
  if (start < 0) return null;
  let end = md.length;
  if (endRe) {
    const rel = md.slice(start + 1).search(endRe);
    if (rel >= 0) end = start + 1 + rel;
  }
  return md.slice(start, end).trim();
}

function buildLessonMd({
  title,
  sourceLabel,
  review,
  study,
  migrationStatus,
  migrationNotes,
}) {
  const notes = migrationNotes?.length ? migrationNotes.join(' ') : '';
  return `# ${title}

> **migrationStatus (з DOCX):** \`${migrationStatus}\`  
> **Джерело:** ${sourceLabel}  
${notes ? `> ${notes}\n` : ''}
## Review Mode

${review}

## Study Mode

${study}

### QA-приклад

Див. відповідний підрозділ «повний приклад» у Study Mode (якщо є в джерелі).

### Failure modes / security / testing / observability / production

Див. розділи failure / security / testing / observability / production у Study Mode.

### Запитання для самоперевірки

Відновіть flow без документа (див. блок «АААА» або hands-on у джерелі).

### Коротка відповідь для співбесіди

Див. **Interview answer** у Study Mode.
`;
}

const auditLog = {};

function recordAudit(topicId, audit, extra = '') {
  auditLog[topicId] = {
    migrationStatus: audit.status,
    migrationNotes: [...audit.notes, extra].filter(Boolean).join(' '),
  };
}

function writeGeneratedRegistry() {
  const lines = [
    '/** Auto-generated by `npm run source:migrate` — не редагуйте вручну */',
    "import type { MigrationStatus } from '../types/topic';",
    '',
    'export type MigrationOverride = { migrationStatus: MigrationStatus; migrationNotes: string };',
    '',
    'export const MIGRATION_OVERRIDE: Record<string, MigrationOverride> = {',
  ];
  for (const [id, v] of Object.entries(auditLog)) {
    const notes = v.migrationNotes.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    lines.push(`  '${id}': { migrationStatus: '${v.migrationStatus}', migrationNotes: '${notes}' },`);
  }
  lines.push('};', '');
  fs.writeFileSync(path.join(root, 'src/data/migration.generated.ts'), lines.join('\n'), 'utf8');
}

async function main() {
  const { kind, text } = await loadPlainText();
  let mammothMd = null;
  if (hasDocx()) {
    const m = await convertDocxToMarkdown();
    mammothMd = m?.markdown ?? null;
  }

  const docxTables = hasDocx() ? 1 : 0; // per-topic refined below
  const globalAudit = { docxTableCount: hasDocx() ? 10 : 0, docxImageCountInSection: 0, sourceKind: kind };

  // Fundamentals
  const fundPlain = extractBetween(
    text,
    '1. AI / LLM Fundamentals — що реально відбувається',
    'PART II. 20 Agentic AI Concepts',
  );
  const fundMammoth =
    mammothMd &&
    sliceMammoth(mammothMd, /1\.\s*AI\s*\/\s*LLM Fundamentals/i, /PART II/i);
  const fundStudy = fundMammoth || studyBodyToMarkdown(fundPlain ?? '');
  const fundAudit = auditTopicContent({
    markdown: fundStudy,
    ...globalAudit,
    docxImageCountInSection: mammothMd ? (fundMammoth?.match(/!\[/g)?.length ?? 0) : 0,
  });
  if (!fundPlain || fundPlain.length < 500) {
    fundAudit.status = 'partial';
    fundAudit.notes.push('Короткий або відсутній витяг Fundamentals — звірте DOCX.');
  }
  fs.writeFileSync(
    path.join(root, 'content/fundamentals/ai-llm-fundamentals.md'),
    buildLessonMd({
      title: 'AI / LLM Fundamentals',
      sourceLabel: kind === 'docx' ? 'DOCX §1 AI / LLM Fundamentals' : 'PDF (DOCX відсутній)',
      review: fundamentalsReview(),
      study: fundStudy,
      migrationStatus: fundAudit.status,
      migrationNotes: fundAudit.notes,
    }),
    'utf8',
  );
  recordAudit('fundamentals', fundAudit);

  // Concepts 1–20
  for (let n = 1; n <= 20; n += 1) {
    const slug = CONCEPT_SLUGS[n];
    const title = CONCEPT_TITLES[n];
    const plain = extractPartIiConcept(text, n);
    const mammothSlice =
      mammothMd &&
      sliceMammoth(
        mammothMd,
        new RegExp(`Concept ${n}\\.`, 'i'),
        n < 20 ? new RegExp(`Concept ${n + 1}\\.`, 'i') : /Практичний курс|LAB 0/i,
      );
    const study = mammothSlice || studyBodyToMarkdown(plain ?? '');
    const review =
      (plain && pickQuickView(plain)) ||
      `Концепція ${n}: ${title} — див. QUICK VIEW і розділ 0 у Study Mode.`;
    const audit = auditTopicContent({
      markdown: study,
      ...globalAudit,
      docxImageCountInSection: mammothSlice?.match(/!\[/g)?.length ?? 0,
    });
    if (!plain || plain.length < 400) {
      audit.status = 'not_migrated';
      audit.notes.push('Секція не знайдена або занадто коротка у джерелі.');
    }
    const id = `concept-${String(n).padStart(2, '0')}`;
    fs.writeFileSync(
      path.join(root, `content/concepts/${String(n).padStart(2, '0')}-${slug}.md`),
      buildLessonMd({
        title: `Concept ${String(n).padStart(2, '0')} — ${title}`,
        sourceLabel: `PART II — Concept ${n} (${kind})`,
        review,
        study,
        migrationStatus: audit.status,
        migrationNotes: audit.notes,
      }),
      'utf8',
    );
    recordAudit(id, audit);
  }

  // Reference
  const refPlain = extractReferenceLibrary(text);
  const refStudy = studyBodyToMarkdown(refPlain ?? '_Reference Library не знайдено в джерелі._');
  const refAudit = auditTopicContent({ markdown: refStudy, ...globalAudit, docxImageCountInSection: 0 });
  if (!refPlain) {
    refAudit.status = 'not_migrated';
    refAudit.notes.push('Reference Library не знайдено.');
  }
  fs.writeFileSync(
    path.join(root, 'content/reference/reference-library.md'),
    buildLessonMd({
      title: 'Reference Library',
      sourceLabel: 'Reference Library',
      review: '_Огляд після перенесення повного розділу._',
      study: refStudy,
      migrationStatus: refAudit.status,
      migrationNotes: refAudit.notes,
    }),
    'utf8',
  );
  recordAudit('reference-library', refAudit);

  // Labs 0–9
  for (let n = 0; n <= 9; n += 1) {
    const plain = extractLab(text, n);
    const study = studyBodyToMarkdown(plain ?? '_Lab не знайдено._');
    const audit = auditTopicContent({ markdown: study, ...globalAudit, docxImageCountInSection: 0 });
    if (!plain || plain.length < 200) {
      audit.status = 'not_migrated';
      audit.notes.push(`Lab ${n} не знайдено або занадто короткий витяг.`);
    }
    const id = `lab-${n}`;
    fs.writeFileSync(
      path.join(root, `content/labs/lab-${n}.md`),
      buildLessonMd({
        title: `Lab ${n} — QA Regression Investigation Agent`,
        sourceLabel: `LAB ${n} (${kind})`,
        review: plain?.split('\n').slice(0, 5).join('\n') || '_Очікує перенесення._',
        study,
        migrationStatus: audit.status,
        migrationNotes: audit.notes,
      }),
      'utf8',
    );
    recordAudit(id, audit);
  }

  writeGeneratedRegistry();
  fs.writeFileSync(
    path.join(root, 'docs/MIGRATION_AUDIT.json'),
    JSON.stringify(auditLog, null, 2),
    'utf8',
  );
  console.log('Migration complete. Wrote content/* and src/data/migration.generated.ts');
}

main();
