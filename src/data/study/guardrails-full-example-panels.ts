function policyDecision(code: string, bodyUk: string): StudyLearnerPanelSection {
  return { type: 'plain', labelUk: 'Що означає рішення', bodyUk: `${code}\n\n${bodyUk}` };
}

function scenarioResult(bodyUk: string): StudyLearnerPanelSection {
  return { type: 'plain', labelUk: 'Що означає рішення', bodyUk };
}

type QaPickItem = {
  key: string;
  titleUk: string;
  teaserUk: string;
  detailUk: string;
};

function fullExampleQaPick(
  labelUk: string,
  pickAriaLabel: string,
  items: QaPickItem[],
): StudyLearnerPanelSection {
  return {
    type: 'processStepPick',
    labelUk,
    pickAriaLabel,
    presentation: 'concepts',
    showActorInPanel: false,
    showStepIndexInPanel: false,
    showNestedCardNumberInPanel: true,
    navLayout: 'sidebar',
    navCompactTitleOnly: true,
    steps: items.map((item) => ({
      key: item.key,
      titleUk: item.titleUk,
      teaserUk: item.teaserUk,
      actorUk: '',
      detailUk: item.detailUk,
    })),
  };
}

