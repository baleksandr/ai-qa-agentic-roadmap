function mcpFramedPlain(labelUk: string, bodyUk: string): StudyLearnerPanelSection {
  return { type: 'plain', labelUk, bodyUk, framed: true };
}

function mcpQa(bodyUk: string): StudyLearnerPanelSection {
  return { type: 'qaCheck', bodyUk };
}

const MCP_PANEL_UI = {
  hidePanelMainCardLabel: true,
  hidePanelStepTitle: true,
} as const;

type McpNestedStep = {
  key: string;
  titleUk: string;
  teaserUk: string;
  bodyUk?: string;
  definitionLead?: { termUk: string; explanationUk: string };
};

function mcpNestedPick(
  labelUk: string,
  pickAriaLabel: string,
  steps: McpNestedStep[],
): StudyLearnerPanelSection {
  return {
    type: 'processStepPick',
    labelUk,
    pickAriaLabel,
    presentation: 'concepts',
    showActorInPanel: false,
    showStepIndexInPanel: false,
    showNestedCardNumberInPanel: true,
    navLayout: 'sidebar',
    navCompactTitleOnly: true,
    steps: steps.map((step) => {
      if (step.definitionLead) {
        return {
          key: step.key,
          titleUk: step.titleUk,
          teaserUk: step.teaserUk,
          actorUk: '',
          detailSections: [
            {
              labelUk: step.titleUk,
              hideLabel: true,
              labeledLead: step.definitionLead,
              ...(step.bodyUk?.trim() ? { bodyUk: step.bodyUk } : {}),
            },
          ],
        };
      }
      return {
        key: step.key,
        titleUk: step.titleUk,
        teaserUk: step.teaserUk,
        actorUk: '',
        detailUk: step.bodyUk ?? '',
      };
    }),
  };
}

function mcpRunPanel(sections: StudyLearnerPanelSection[], terms?: StudyPanelTermEntry[]): FundamentalsCardPanel {
  return { sections, terms };
}

function mcpWhyPanel(sections: StudyLearnerPanelSection[], terms?: StudyPanelTermEntry[]): FundamentalsCardPanel {
  return { sections, terms };
}

