function ftFramedPlain(labelUk: string, bodyUk: string): StudyLearnerPanelSection {
  return { type: 'plain', labelUk, bodyUk, framed: true };
}

function ftQa(bodyUk: string): StudyLearnerPanelSection {
  return { type: 'qaCheck', bodyUk };
}

const FT_PANEL_UI = {
  hidePanelMainCardLabel: true,
  hidePanelStepTitle: true,
} as const;

type FtNestedDetailSection = {
  labelUk: string;
  bodyUk: string;
};

type FtNestedStep = {
  key: string;
  titleUk: string;
  teaserUk: string;
  bodyUk?: string;
  detailSections?: FtNestedDetailSection[];
};

function ftNestedPick(
  labelUk: string,
  pickAriaLabel: string,
  steps: FtNestedStep[],
): StudyLearnerPanelSection {
  return {
    type: 'processStepPick',
    labelUk,
    pickAriaLabel,
    presentation: 'concepts',
    showActorInPanel: false,
    showStepIndexInPanel: false,
    showNestedCardNumberInPanel: true,
    navLayout: 'sidebar',
    navCompactTitleOnly: true,
    steps: steps.map((step) => ({
      key: step.key,
      titleUk: step.titleUk,
      teaserUk: step.teaserUk,
      actorUk: '',
      ...(step.detailSections?.length
        ? { detailSections: step.detailSections }
        : { detailUk: step.bodyUk ?? '' }),
    })),
  };
}

function ftConceptPanel(
  sections: StudyLearnerPanelSection[],
  terms?: StudyPanelTermEntry[],
): FundamentalsCardPanel {
  return { sections, terms };
}

