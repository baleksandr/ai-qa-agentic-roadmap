function maFramedPlain(labelUk: string, bodyUk: string): StudyLearnerPanelSection {
  return { type: 'plain', labelUk, bodyUk, framed: true };
}

const MA_PANEL_UI = {
  hidePanelMainCardLabel: true,
  hidePanelStepTitle: true,
} as const;

function maPanel(sections: StudyLearnerPanelSection[], terms?: StudyPanelTermEntry[]): FundamentalsCardPanel {
  return { sections, terms };
}

function maRolePanel(blocks: {
  goalUk: string;
  inputUk: string;
  doesUk: string;
  forwardUk: string;
  accessUk: string;
  qaUk: string;
  terms: StudyPanelTermEntry[];
}): FundamentalsCardPanel {
  return maPanel(
    [
      maFramedPlain('Мета', blocks.goalUk),
      maFramedPlain('Що має на вході', blocks.inputUk),
      maFramedPlain('Що робить', blocks.doesUk),
      maFramedPlain('Що передає далі', blocks.forwardUk),
      maFramedPlain('Межі доступу', blocks.accessUk),
      maFramedPlain('Що перевіряє QA', blocks.qaUk),
    ],
    blocks.terms,
  );
}

function maExampleStepPanel(blocks: {
  inputUk: string;
  actionUk: string;
  resultUk: string;
  qaUk: string;
  terms: StudyPanelTermEntry[];
}): FundamentalsCardPanel {
  return maPanel(
    [
      maFramedPlain('Вхід', blocks.inputUk),
      maFramedPlain('Дія', blocks.actionUk),
      maFramedPlain('Результат', blocks.resultUk),
      maFramedPlain('Що перевіряє QA', blocks.qaUk),
    ],
    blocks.terms,
  );
}

function maLlmRolePanel(blocks: {
  understandUk: string;
  whoUk: string;
  happensUk: string;
  forwardUk: string;
  qaUk: string;
  exampleUk?: string;
  terms: StudyPanelTermEntry[];
}): FundamentalsCardPanel {
  const sections: StudyLearnerPanelSection[] = [
    maFramedPlain('Що я зрозумію', blocks.understandUk),
    maFramedPlain('Хто діє', blocks.whoUk),
    maFramedPlain('Що відбувається', blocks.happensUk),
  ];
  if (blocks.exampleUk?.trim()) {
    sections.push(maFramedPlain('Приклад ABC-123', blocks.exampleUk));
  }
  sections.push(
    maFramedPlain('Що передає далі', blocks.forwardUk),
    maFramedPlain('Що перевіряє QA', blocks.qaUk),
  );
  return maPanel(sections, blocks.terms);
}

function maFailurePanel(blocks: {
  understandUk: string;
  happenedUk: string;
  problemUk: string;
  systemUk: string;
  qaUk: string;
  terms: StudyPanelTermEntry[];
}): FundamentalsCardPanel {
  return maPanel(
    [
      maFramedPlain('Що я зрозумію', blocks.understandUk),
      maFramedPlain('Що сталося', blocks.happenedUk),
      maFramedPlain('Чому це проблема', blocks.problemUk),
      maFramedPlain('Як має діяти система', blocks.systemUk),
      maFramedPlain('Як перевіряє QA', blocks.qaUk),
    ],
    blocks.terms,
  );
}

