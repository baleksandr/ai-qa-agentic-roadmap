function framedPlain(labelUk: string, bodyUk: string): StudyLearnerPanelSection {
  return { type: 'plain', labelUk, bodyUk, framed: true };
}

const VECTOR_DB_PANEL_UI = {
  hidePanelMainCardLabel: true,
  hidePanelStepTitle: true,
} as const;

function vdWhyPanel(blocks: {
  plainUk: string;
  exampleUk: string;
  qaUk: string;
  terms: StudyPanelTermEntry[];
  prepStepPick?: StudyLearnerPanelSection;
}): FundamentalsCardPanel {
  const sections: StudyLearnerPanelSection[] = [
    framedPlain('Простими словами', blocks.plainUk),
  ];
  if (blocks.prepStepPick) {
    sections.push(blocks.prepStepPick);
  }
  sections.push(
    framedPlain('Приклад login_spec', blocks.exampleUk),
    framedPlain('Що перевіряє QA', blocks.qaUk),
  );
  return { sections, terms: blocks.terms };
}

