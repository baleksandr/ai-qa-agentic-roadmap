function a2aFramedPlain(labelUk: string, bodyUk: string): StudyLearnerPanelSection {
  return { type: 'plain', labelUk, bodyUk, framed: true };
}

const A2A_PANEL_UI = {
  hidePanelMainCardLabel: true,
  hidePanelStepTitle: true,
} as const;

function a2aPanel(sections: StudyLearnerPanelSection[], terms?: StudyPanelTermEntry[]): FundamentalsCardPanel {
  return { sections, terms };
}

function a2aConceptPanel(blocks: {
  bodySections: { labelUk: string; bodyUk: string }[];
  terms: StudyPanelTermEntry[];
}): FundamentalsCardPanel {
  return a2aPanel(
    blocks.bodySections.map((s) => a2aFramedPlain(s.labelUk, s.bodyUk)),
    blocks.terms,
  );
}

function a2aFailurePanel(blocks: {
  happenedUk: string;
  whyUk: string;
  systemUk: string;
  qaUk: string;
  terms: StudyPanelTermEntry[];
}): FundamentalsCardPanel {
  return a2aPanel(
    [
      a2aFramedPlain('Що сталося', blocks.happenedUk),
      a2aFramedPlain('Чому це небезпечно', blocks.whyUk),
      a2aFramedPlain('Як має діяти код', blocks.systemUk),
      a2aFramedPlain('Як перевіряє QA', blocks.qaUk),
    ],
    blocks.terms,
  );
}

