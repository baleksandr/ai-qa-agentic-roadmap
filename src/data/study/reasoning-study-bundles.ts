type MechanismPassMiniCard = {
  titleUk: string;
  bodyUk: string;
  tone?: StudyLearnerPanelMiniCardTone;
};

function mechanismRolePanel(blocks: {
  plainUk: string;
  exampleUk: string;
  passesPlainUk?: string;
  passesMiniCards?: MechanismPassMiniCard[];
  qaUk: string;
  terms: StudyPanelTermEntry[];
}): FundamentalsCardPanel {
  const sections: FundamentalsCardPanel['sections'] = [
    { type: 'plain', labelUk: 'Простими словами', bodyUk: blocks.plainUk },
    { type: 'plain', labelUk: 'На прикладі login_spec', bodyUk: blocks.exampleUk },
  ];
  if (blocks.passesMiniCards?.length) {
    sections.push({
      type: 'miniCards',
      labelUk: 'Що передає далі',
      layout: 'titledStack',
      items: blocks.passesMiniCards,
    });
  } else if (blocks.passesPlainUk) {
    sections.push({
      type: 'plain',
      labelUk: 'Що передає далі',
      bodyUk: blocks.passesPlainUk,
    });
  }
  sections.push({ type: 'plain', labelUk: 'Що перевіряє QA', bodyUk: blocks.qaUk });
  return { sections, terms: blocks.terms };
}

function sequenceDetailPanel(blocks: {
  situationUk: string;
  whoUk: string;
  nextMiniCards: MechanismPassMiniCard[];
  exampleUk: string;
  qaUk: string;
}): FundamentalsCardPanel {
  return {
    sections: [
      { type: 'plain', labelUk: 'Ситуація', bodyUk: blocks.situationUk },
      { type: 'plain', labelUk: 'Хто що робить', bodyUk: blocks.whoUk },
      {
        type: 'miniCards',
        labelUk: 'Що може статися далі',
        layout: 'titledStack',
        items: blocks.nextMiniCards.map((card) => ({
          ...card,
          tone: card.tone ?? 'neutral',
        })),
      },
      { type: 'plain', labelUk: 'Приклад відповіді', bodyUk: blocks.exampleUk },
      { type: 'plain', labelUk: 'Що перевіряє QA', bodyUk: blocks.qaUk },
    ],
  };
}

