type MsgFieldSection = {
  labelUk: string;
  bodyUk?: string;
  hideLabel?: boolean;
  labeledPairs?: Array<{ termUk: string; explanationUk: string }>;
  compactPayload?: Array<{ keyUk: string; valueUk: string }>;
  compactPayloadFootnoteUk?: string;
};

const S4_NESTED_PICK_OPTS = { flatDetailPanels: true } as const;

type ExamplePayloadField = { keyUk: string; valueUk: string };

function fieldPanelSections(opts: {
  plainUk: string;
  exampleUk: string;
  examplePayloadFields?: ExamplePayloadField[];
  examplePayloadFootnoteUk?: string;
  qaBullets: string[];
  terms: Array<{ termUk: string; explanationUk: string }>;
}): MsgFieldSection[] {
  const exampleSection: MsgFieldSection = opts.examplePayloadFields?.length
    ? {
        labelUk: 'Приклад login_spec',
        bodyUk: opts.exampleUk,
        compactPayload: opts.examplePayloadFields,
        compactPayloadFootnoteUk: opts.examplePayloadFootnoteUk,
      }
    : { labelUk: 'Приклад login_spec', bodyUk: opts.exampleUk };

  const sections: MsgFieldSection[] = [
    { labelUk: 'Простими словами', bodyUk: opts.plainUk },
    exampleSection,
  ];
  if (opts.qaBullets.length > 0) {
    sections.push({ labelUk: 'Що перевіряє QA', bodyUk: qaBulletBody(opts.qaBullets) });
  }
  if (opts.terms.length > 0) {
    sections.push({ labelUk: 'Термінологія', labeledPairs: opts.terms });
  }
  return sections;
}

function msgFieldRichStep(
  key: string,
  titleUk: string,
  teaserUk: string,
  sections: MsgFieldSection[],
) {
  return { key, titleUk, teaserUk, sections };
}

function msgFieldStep(key: string, titleUk: string, teaserUk: string, bodyUk: string) {
  return msgFieldRichStep(key, titleUk, teaserUk, [{ labelUk: 'Пояснення', bodyUk }]);
}

