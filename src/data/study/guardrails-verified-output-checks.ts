type CheckSection = {
  labelUk: string;
  bodyUk?: string;
  labeledPairs?: Array<{ termUk: string; explanationUk: string }>;
};

function qaBlocks(items: Array<{ titleUk: string; bodyUk: string }>): CheckSection[] {
  return [
    { labelUk: 'Що перевіряє QA', bodyUk: '' },
    ...items.map((item) => ({ labelUk: item.titleUk, bodyUk: item.bodyUk })),
  ];
}

function checkStep(
  key: string,
  titleUk: string,
  teaserUk: string,
  sections: CheckSection[],
) {
  return { key, titleUk, teaserUk, sections };
}

