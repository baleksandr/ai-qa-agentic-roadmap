function awFramedPlain(labelUk: string, bodyUk: string): StudyLearnerPanelSection {
  return { type: 'plain', labelUk, bodyUk, framed: true };
}

const AW_PANEL_UI = {
  hidePanelMainCardLabel: true,
  hidePanelStepTitle: true,
} as const;

function awPanel(sections: StudyLearnerPanelSection[], terms?: StudyPanelTermEntry[]): FundamentalsCardPanel {
  return { sections, terms };
}

function awStagePanel(blocks: {
  inputUk: string;
  doesUk: string;
  forwardUk: string;
  qaUk: string;
  terms: StudyPanelTermEntry[];
}): FundamentalsCardPanel {
  return awPanel(
    [
      awFramedPlain('Що має на вході', blocks.inputUk),
      awFramedPlain('Що робить', blocks.doesUk),
      awFramedPlain('Що передає далі', blocks.forwardUk),
      awFramedPlain('Що перевіряє QA', blocks.qaUk),
    ],
    blocks.terms,
  );
}

function awComparePanel(blocks: {
  questionUk: string;
  describesUk: string;
  exampleUk: string;
  qaUk: string;
  terms: StudyPanelTermEntry[];
}): FundamentalsCardPanel {
  return awPanel(
    [
      awFramedPlain('Головне питання', blocks.questionUk),
      awFramedPlain('Що описує', blocks.describesUk),
      awFramedPlain('Приклад ABC-123', blocks.exampleUk),
      awFramedPlain('Що перевіряє QA', blocks.qaUk),
    ],
    blocks.terms,
  );
}

function awFailurePanel(blocks: {
  happenedUk: string;
  problemUk: string;
  systemUk: string;
  qaUk: string;
  terms: StudyPanelTermEntry[];
  extraSections?: StudyLearnerPanelSection[];
}): FundamentalsCardPanel {
  const sections: StudyLearnerPanelSection[] = [
    awFramedPlain('Що сталося', blocks.happenedUk),
    awFramedPlain('Чому це проблема', blocks.problemUk),
    awFramedPlain('Як має діяти система', blocks.systemUk),
    awFramedPlain('Як перевіряє QA', blocks.qaUk),
  ];
  if (blocks.extraSections?.length) {
    sections.push(...blocks.extraSections);
  }
  return awPanel(sections, blocks.terms);
}

function awProductionPanel(blocks: {
  whyUk: string;
  howUk: string;
  exampleUk: string;
  qaUk: string;
  terms: StudyPanelTermEntry[];
}): FundamentalsCardPanel {
  return awPanel(
    [
      awFramedPlain('Навіщо це потрібно', blocks.whyUk),
      awFramedPlain('Як працює', blocks.howUk),
      awFramedPlain('Приклад ABC-123', blocks.exampleUk),
      awFramedPlain('Що перевіряє QA', blocks.qaUk),
    ],
    blocks.terms,
  );
}

