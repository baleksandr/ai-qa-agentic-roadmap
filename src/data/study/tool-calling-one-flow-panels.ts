import type { FundamentalsCardPanel } from './fundamentals-card-panels';
import type { StudyLearnerPanelMiniCardsSection } from './study-learner-panel-sections';

const flowBranchNextSection = (
  items: StudyLearnerPanelMiniCardsSection['items'],
): StudyLearnerPanelMiniCardsSection => ({
  type: 'miniCards',
  labelUk: 'Що передає далі',
  layout: 'titledStack',
  items,
});

const oneFlowStepPanel = (
  whoUk: string,
  inputUk: string,
  doesUk: string,
  next:
    | { branches: StudyLearnerPanelMiniCardsSection['items'] }
    | { plainUk: string },
  qaUk: string,
  terms?: FundamentalsCardPanel['terms'],
): FundamentalsCardPanel => ({
  sections: [
    { type: 'plain', labelUk: 'Хто діє', bodyUk: whoUk },
    { type: 'plain', labelUk: 'Що має на вході', bodyUk: inputUk },
    { type: 'plain', labelUk: 'Що робить', bodyUk: doesUk },
    'branches' in next
      ? flowBranchNextSection(next.branches)
      : { type: 'plain', labelUk: 'Що передає далі', bodyUk: next.plainUk },
    { type: 'plain', labelUk: 'Що перевіряє QA', bodyUk: qaUk },
  ],
  terms,
});

