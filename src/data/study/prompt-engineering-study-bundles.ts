function pePartsCardPanel(
  plainUk: string,
  exampleLabelUk: string,
  exampleUk: string,
  failureUk: string,
  qaCheckUk: string,
  terms: StudyPanelTermEntry[],
  extraSections?: FundamentalsCardPanel['sections'],
): FundamentalsCardPanel {
  return {
    sections: [
      { type: 'plain', labelUk: 'Простими словами', bodyUk: plainUk },
      { type: 'plain', labelUk: exampleLabelUk, bodyUk: exampleUk },
      ...(extraSections ?? []),
      { type: 'plain', labelUk: 'Що може піти не так', bodyUk: failureUk },
      { type: 'qaCheck', bodyUk: qaCheckUk },
    ],
    terms,
  };
}

function pePanel(
  whatUk: string,
  exampleUk: string,
  failureUk: string,
  qaCheckUk: string,
  terms: StudyPanelTermEntry[],
  inputOutputUk?: string,
): FundamentalsCardPanel {
  const sections: FundamentalsCardPanel['sections'] = [
    { type: 'plain', labelUk: 'Простими словами', bodyUk: whatUk },
  ];
  if (inputOutputUk?.trim()) {
    sections.push({ type: 'plain', labelUk: 'Вхід і результат', bodyUk: inputOutputUk });
  }
  sections.push(
    { type: 'plain', labelUk: 'Приклад', bodyUk: exampleUk },
    { type: 'plain', labelUk: 'Що може піти не так', bodyUk: failureUk },
    { type: 'qaCheck', bodyUk: qaCheckUk },
  );
  return { sections, terms };
}

