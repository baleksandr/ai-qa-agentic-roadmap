import type { StudyLearnerPanelSection } from './study-learner-panel-sections';
import { guardrailsNestedPick } from './guardrails-panel-helpers';

type VerdictSection = {
  labelUk: string;
  bodyUk?: string;
  labeledPairs?: Array<{ termUk: string; explanationUk: string }>;
};

function qaSectionBlocks(
  items: Array<{ titleUk: string; bodyUk: string }>,
): VerdictSection[] {
  return [
    { labelUk: 'Що перевіряє QA', bodyUk: '' },
    ...items.map((item) => ({ labelUk: item.titleUk, bodyUk: item.bodyUk })),
  ];
}

function verdictStep(
  key: string,
  titleUk: string,
  teaserUk: string,
  sections: VerdictSection[],
) {
  return { key, titleUk, teaserUk, sections };
}

