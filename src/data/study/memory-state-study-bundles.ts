function framedPlain(labelUk: string, bodyUk: string): StudyLearnerPanelSection {
  return { type: 'plain', labelUk, bodyUk, framed: true };
}

const MEMORY_STATE_PANEL_UI = {
  hidePanelMainCardLabel: true,
  hidePanelStepTitle: true,
} as const;

type MemoryStateQaActionStep = { key: string; titleUk: string; teaserUk: string; bodyUk: string };

function memoryStateQaActionStepPick(
  pickAriaLabel: string,
  steps: MemoryStateQaActionStep[],
): StudyLearnerPanelSection {
  return {
    type: 'processStepPick',
    labelUk: 'Що робить QA',
    pickAriaLabel,
    presentation: 'concepts',
    showActorInPanel: false,
    showStepIndexInPanel: false,
    showNestedCardNumberInPanel: false,
    navLayout: 'sidebar',
    navCompactTitleOnly: true,
    steps: steps.map((step) => ({
      key: step.key,
      titleUk: step.titleUk,
      teaserUk: step.teaserUk,
      actorUk: '',
      detailUk: step.bodyUk,
    })),
  };
}

function memoryStateFailurePanel(blocks: {
  situationUk: string;
  whyUk: string;
  codeUk: string;
  qaPickAriaLabel: string;
  qaPickSteps: MemoryStateQaActionStep[];
  terms?: FundamentalsCardPanel['terms'];
  qaAsideUk?: { labelUk: string; bodyUk: string };
}): FundamentalsCardPanel {
  const framed = (
    labelUk: string,
    bodyUk: string,
    framedVariant?: 'why',
  ): StudyLearnerPanelSection => ({
    type: 'plain',
    labelUk,
    bodyUk,
    framed: true,
    framedVariant,
  });

  const sections: StudyLearnerPanelSection[] = [
    framed('Ситуація', blocks.situationUk),
    framed('Чому це проблема', blocks.whyUk, 'why'),
    framed('Як має поводитися код', blocks.codeUk),
    memoryStateQaActionStepPick(blocks.qaPickAriaLabel, blocks.qaPickSteps),
  ];

  if (blocks.qaAsideUk?.bodyUk.trim()) {
    sections.push(framed(blocks.qaAsideUk.labelUk, blocks.qaAsideUk.bodyUk));
  }

  return {
    sections,
    terms: blocks.terms ?? [],
  };
}

function memoryQaFramed(
  labelUk: string,
  bodyUk: string,
  framedVariant?: 'expect' | 'limit',
): StudyLearnerPanelSection {
  return { type: 'plain', labelUk, bodyUk, framed: true, framedVariant };
}

function memoryQaTestingPanel(blocks: {
  checkUk: string;
  prepareUk: string;
  qaSection: StudyLearnerPanelSection;
  expectUk: string;
  resultUk: string;
  limitUk?: string;
}): FundamentalsCardPanel {
  const sections: StudyLearnerPanelSection[] = [
    memoryQaFramed('Що перевіряємо', blocks.checkUk),
    memoryQaFramed('Що підготувати', blocks.prepareUk),
    blocks.qaSection,
    memoryQaFramed('Очікування', blocks.expectUk, 'expect'),
    memoryQaFramed('Як побачити результат', blocks.resultUk),
  ];
  if (blocks.limitUk?.trim()) {
    sections.push(memoryQaFramed('Важлива межа', blocks.limitUk, 'limit'));
  }
  return { sections, terms: [] };
}

function memoryWhyPanel(
  termUk: string,
  definitionUk: string,
  blocks: Array<{ labelUk: string; bodyUk: string }>,
  qaUk: string,
): FundamentalsCardPanel {
  return {
    sections: [
      { type: 'termDefinition', termUk, explanationUk: definitionUk },
      ...blocks.map((b) => framedPlain(b.labelUk, b.bodyUk)),
      { type: 'qaCheck', bodyUk: qaUk },
    ],
  };
}

