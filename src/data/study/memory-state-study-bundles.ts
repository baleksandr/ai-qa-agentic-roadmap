type MemorySequenceStepContent = {
  incomingUk: string;
  actorLabelUk: string;
  actorUk: string;
  changesUk: string;
  nextUk: string;
  qaUk: string;
  turnLoopHintUk?: string;
};

function memorySequenceStepPanel(content: MemorySequenceStepContent): FundamentalsCardPanel {
  const sections: StudyLearnerPanelSection[] = [
    framedPlain('Що надходить', content.incomingUk),
    framedPlain(content.actorLabelUk, content.actorUk),
    framedPlain('Що змінюється', content.changesUk),
    framedPlain('Куди далі', content.nextUk),
    { type: 'qaCheck', bodyUk: content.qaUk },
  ];
  if (content.turnLoopHintUk?.trim()) {
    sections.push({
      type: 'cardIntent',
      hideLabel: true,
      bodyUk: content.turnLoopHintUk,
    });
  }
  return { sections };
}

