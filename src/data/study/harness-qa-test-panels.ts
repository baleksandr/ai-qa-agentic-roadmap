const QA_NESTED_HINT_UK =
  'Оберіть перевірку, щоб прочитати пояснення та очікування. На телефоні воно з’явиться під картками.';

const qaStep = (
  key: string,
  titleUk: string,
  teaserUk: string,
  panelUk: string,
  expectUk: string,
): StudyLearnerPanelProcessStepPickSection['steps'][number] => ({
  key,
  titleUk,
  teaserUk,
  actorUk: '',
  detailUk: panelUk,
  detailSections: [{ labelUk: 'Очікування', bodyUk: expectUk }],
});

const qaNestedPick = (
  labelUk: string,
  pickAriaLabel: string,
  steps: StudyLearnerPanelProcessStepPickSection['steps'],
  pickConclusionUk?: string,
): StudyLearnerPanelSection => ({
  type: 'processStepPick',
  labelUk,
  pickAriaLabel,
  presentation: 'concepts',
  showActorInPanel: false,
  showStepIndexInPanel: false,
  navLayout: 'sidebar',
  interactionHintUk: QA_NESTED_HINT_UK,
  steps,
  pickConclusionUk,
});

const qaCard = (
  nested: StudyLearnerPanelSection,
  terms: StudyPanelTermEntry[] = [],
): FundamentalsCardPanel => ({
  sections: [nested],
  terms,
});

