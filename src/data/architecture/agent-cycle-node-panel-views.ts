export function getAgentNodePanelView(nodeId: string, labelUk: string): AgentNodePanelView | null {
  const custom = LOGIN_SPEC_NODE_VIEWS[nodeId];
  if (custom) {
    return { ...custom, titleUk: custom.titleUk || labelUk };
  }
  const base = getArchitectureNodePanel('agent', nodeId);
  if (!base) return null;
  return {
    titleUk: labelUk,
    panelKind: 'actor',
    happensUk: base.what,
    receivesUk: base.input ?? undefined,
    sendsUk: base.output ?? base.recipient ?? '—',
    qaUk: base.qaAgent ?? base.risks ?? '—',
  };
}
